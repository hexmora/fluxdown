import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const requirePrism = createRequire(
  new URL('../packages/react-plugins/package.json', import.meta.url),
);
const components = requirePrism('prismjs/components.json') as {
  languages: Record<string, unknown>;
};
const getLoader = requirePrism('prismjs/dependencies.js') as (
  components: object,
  languages: string[],
) => { getIds(): string[] };

// next-raw's full Prism bundle includes every language component and its extras.
// Let Prism order required, optional, and modifying components together.
const languages = Object.keys(components.languages).filter((id) => id !== 'meta');
const imports = getLoader(components, languages)
  .getIds()
  .map((id) => `import 'prismjs/components/prism-${id}.js';`);

await writeFile(
  new URL(
    '../packages/react-plugins/src/plugins/code-prism/slot/code-prism/renderer/languages.ts',
    import.meta.url,
  ),
  [
    '/* eslint-disable perfectionist/sort-imports -- Prism components must load in dependency order. */',
    '// Generated by: pnpm exec tsx scripts/generate-prism-languages.ts',
    '// Match next-raw/src/packs/plugins/slot/code-highlighter/static/prism.js: all languages and extras.',
    '// Import only after the shared Prism runtime has initialized.',
    ...imports,
    '',
  ].join('\n'),
);
